#!/usr/bin/env bash
# Regenerate one tap file.
#
#   scripts/update.sh formula sock 1.2.3      -> Formula/sock.rb from sock-cli v1.2.3
#   scripts/update.sh formula sock-mcp 1.2.3  -> Formula/sock-mcp.rb from sock-mcp v1.2.3
#   scripts/update.sh cask sock               -> Casks/sock.rb from latest/mac.json
#
# Formulas build from the GitHub tag source tarball; the cask installs the dmg
# named by the live manifest. Writes only that file, and only when its tarball
# or manifest is present and well formed. Callers commit and push.
# Runs on bash 3.2 (macOS /bin/bash): no associative arrays.
set -euo pipefail

base=${DOWNLOADS_URL:-https://downloads.joinsock.com}
archive=${GITHUB_ARCHIVE_URL:-https://github.com/Aeryx-ai}
tap=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

die() {
  echo "update.sh: $*" >&2
  exit 1
}

usage() { die "usage: update.sh formula sock|sock-mcp <version> | cask sock"; }

# field <file> <key>: the string value of key in a flat manifest.
field() {
  sed -n "s/.*\"$2\"[[:space:]]*:[[:space:]]*\"\([^\"]*\)\".*/\1/p" "$1" | head -n 1
}

# fetch <platform>: download and validate a manifest, setting url, sha and ver.
fetch() {
  local m=$work/$1.json
  curl -fsSL --retry 3 --retry-delay 2 -A "aeryx-homebrew-tap/update.sh" \
    -o "$m" "$base/latest/$1.json" 2>/dev/null ||
    die "manifest $1 not available at $base/latest/$1.json"
  url=$(field "$m" url)
  sha=$(field "$m" sha256)
  ver=$(field "$m" version)
  [[ $url == https://* ]] || die "manifest $1: bad url [$url]"
  [[ $sha =~ ^[0-9a-f]{64}$ ]] || die "manifest $1: bad sha256 [$sha]"
  [[ $ver =~ ^[0-9]+(\.[0-9]+)+$ ]] || die "manifest $1: bad version [$ver]"
}

# place <dest> <generated>: move the generated file into the tap.
place() {
  mkdir -p "$(dirname "$1")"
  mv "$2" "$1"
  echo "wrote ${1#"$tap"/}"
}

# formula <name> <repo> <class> <desc> <test body> <version>: a build from
# the signed v<version> tag's source tarball.
formula() {
  local name=$1 repo=$2 class=$3 desc=$4 test=$5 version=$6
  [[ $version =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "$name: bad version [$version], want X.Y.Z without v"
  local path=$repo/archive/refs/tags/v$version.tar.gz tgz=$work/src.tar.gz
  curl -fsSL --retry 3 --retry-delay 2 -A "aeryx-homebrew-tap/update.sh" \
    -o "$tgz" "$archive/$path" 2>/dev/null ||
    die "$name: tarball not available at $archive/$path"
  local sha
  sha=$(shasum -a 256 "$tgz" | cut -d' ' -f1)
  [[ $sha =~ ^[0-9a-f]{64}$ ]] || die "$name: could not hash $path"
  local out=$work/out.rb
  cat >"$out" <<EOF
# Generated by scripts/update.sh from the $repo v$version tag. Do not edit.
class $class < Formula
  desc "$desc"
  homepage "https://joinsock.com"
  url "https://github.com/Aeryx-ai/$path"
  sha256 "$sha"
  license "MIT"
  head "https://github.com/Aeryx-ai/$repo.git", branch: "main"

  depends_on "go" => :build

  def install
    system "go", "build", *std_go_args(ldflags: "-s -w -X main.version=#{version}"), "./cmd/$name"
  end

  test do
    $test
  end
end
EOF
  place "$tap/Formula/$name.rb" "$out"
}

cask() {
  fetch mac
  # brew audit wants the version interpolated into a versioned url.
  local vurl=${url//"$ver"/'#{version}'}
  local out=$work/out.rb
  cat >"$out" <<EOF
# Generated by scripts/update.sh from the mac manifest. Do not edit.
cask "sock" do
  version "$ver"
  sha256 "$sha"

  url "$vurl"
  name "Sock"
  desc "Messaging between people and their agents"
  homepage "https://joinsock.com/"

  livecheck do
    url "https://downloads.joinsock.com/latest/mac-appcast.xml"
    strategy :sparkle, &:short_version
  end

  auto_updates true
  depends_on macos: :tahoe

  app "Sock.app"

  zap trash: [
    "~/Library/Application Scripts/ai.aeryx.sock",
    "~/Library/Application Scripts/ai.aeryx.sock.notifications",
    "~/Library/Application Scripts/group.ai.aeryx.sock",
    "~/Library/Caches/ai.aeryx.sock",
    "~/Library/Containers/ai.aeryx.sock",
    "~/Library/Containers/ai.aeryx.sock.notifications",
    "~/Library/Group Containers/group.ai.aeryx.sock",
    "~/Library/HTTPStorages/ai.aeryx.sock",
    "~/Library/Preferences/ai.aeryx.sock.plist",
  ]
end
EOF
  place "$tap/Casks/sock.rb" "$out"
}

case "$#:${1:-} ${2:-}" in
"3:formula sock")
  formula sock sock-cli Sock "Message your owner and conversations from scripts, jobs and agents" \
    'assert_match version.to_s, shell_output("#{bin}/sock --version")' "$3"
  ;;
"3:formula sock-mcp")
  # sock-mcp has no version flag; --help prints its flags and exits 1.
  formula sock-mcp sock-mcp SockMcp "MCP server that lets an agent message through sock as a puppet" \
    'assert_match "outbound-only", shell_output("#{bin}/sock-mcp --help 2>&1", 1)' "$3"
  ;;
"2:cask sock") cask ;;
*) usage ;;
esac
