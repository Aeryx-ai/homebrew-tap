#!/usr/bin/env bash
# Regenerate one tap file from the live latest/<platform>.json manifests.
#
#   scripts/update.sh formula sock      -> Formula/sock.rb
#   scripts/update.sh formula sock-mcp  -> Formula/sock-mcp.rb
#   scripts/update.sh cask sock         -> Casks/sock.rb
#
# Writes only that file, and only when every manifest it needs is present,
# well formed and (for a formula) agrees on one version. Callers commit and push.
# Runs on bash 3.2 (macOS /bin/bash): no associative arrays.
set -euo pipefail

base=${DOWNLOADS_URL:-https://downloads.joinsock.com}
tap=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

die() {
  echo "update.sh: $*" >&2
  exit 1
}

usage() { die "usage: update.sh formula sock|sock-mcp | cask sock"; }

# field <file> <key>: the string value of key in a flat manifest.
field() {
  sed -n "s/.*\"$2\"[[:space:]]*:[[:space:]]*\"\([^\"]*\)\".*/\1/p" "$1" | head -n 1
}

# fetch <platform>: download and validate a manifest, setting url, sha and ver.
fetch() {
  local m=$work/$1.json
  curl -fsSL --retry 3 --retry-delay 2 -A "aeryx-homebrew-tap/update.sh" \
    -o "$m" "$base/latest/$1.json" 2>/dev/null ||
    die "manifest $1 not available at $base/latest/$1.json"
  url=$(field "$m" url)
  sha=$(field "$m" sha256)
  ver=$(field "$m" version)
  [[ $url == https://* ]] || die "manifest $1: bad url [$url]"
  [[ $sha =~ ^[0-9a-f]{64}$ ]] || die "manifest $1: bad sha256 [$sha]"
  [[ $ver =~ ^[0-9]+(\.[0-9]+)+$ ]] || die "manifest $1: bad version [$ver]"
}

# place <dest> <generated>: move the generated file into the tap.
place() {
  mkdir -p "$(dirname "$1")"
  mv "$2" "$1"
  echo "wrote ${1#"$tap"/}"
}

# formula <name> <platform prefix> <class> <desc> <test body>
formula() {
  local name=$1 prefix=$2 class=$3 desc=$4 test=$5 version="" os arch
  for os in darwin linux; do
    for arch in arm64 amd64; do
      fetch "$prefix-$os-$arch"
      [[ -z $version || $version == "$ver" ]] ||
        die "$name: version mismatch ($prefix-$os-$arch is $ver, others $version)"
      version=$ver
      printf -v "url_${os}_$arch" %s "$url"
      printf -v "sha_${os}_$arch" %s "$sha"
    done
  done
  local out=$work/out.rb
  # url_* and sha_* are assigned by printf -v above.
  # shellcheck disable=SC2154
  cat >"$out" <<EOF
# Generated by scripts/update.sh from the $prefix-* manifests. Do not edit.
class $class < Formula
  desc "$desc"
  homepage "https://joinsock.com"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$url_darwin_arm64"
      sha256 "$sha_darwin_arm64"
    end
    on_intel do
      url "$url_darwin_amd64"
      sha256 "$sha_darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$url_linux_arm64"
      sha256 "$sha_linux_arm64"
    end
    on_intel do
      url "$url_linux_amd64"
      sha256 "$sha_linux_amd64"
    end
  end

  def install
    bin.install "$name"
  end

  test do
    $test
  end
end
EOF
  place "$tap/Formula/$name.rb" "$out"
}

cask() {
  fetch mac
  # brew audit wants the version interpolated into a versioned url.
  local vurl=${url//"$ver"/'#{version}'}
  local out=$work/out.rb
  cat >"$out" <<EOF
# Generated by scripts/update.sh from the mac manifest. Do not edit.
cask "sock" do
  version "$ver"
  sha256 "$sha"

  url "$vurl"
  name "Sock"
  desc "Messaging between people and their agents"
  homepage "https://joinsock.com/"

  livecheck do
    url "https://downloads.joinsock.com/latest/mac-appcast.xml"
    strategy :sparkle, &:short_version
  end

  auto_updates true
  depends_on macos: :tahoe

  app "Sock.app"

  zap trash: [
    "~/Library/Application Scripts/ai.aeryx.sock",
    "~/Library/Application Scripts/ai.aeryx.sock.notifications",
    "~/Library/Application Scripts/group.ai.aeryx.sock",
    "~/Library/Caches/ai.aeryx.sock",
    "~/Library/Containers/ai.aeryx.sock",
    "~/Library/Containers/ai.aeryx.sock.notifications",
    "~/Library/Group Containers/group.ai.aeryx.sock",
    "~/Library/HTTPStorages/ai.aeryx.sock",
    "~/Library/Preferences/ai.aeryx.sock.plist",
  ]
end
EOF
  place "$tap/Casks/sock.rb" "$out"
}

[[ $# -eq 2 ]] || usage
case "$1 $2" in
"formula sock")
  formula sock cli Sock "Message your owner and conversations from scripts, jobs and agents" \
    'assert_match version.to_s, shell_output("#{bin}/sock --version")'
  ;;
"formula sock-mcp")
  # sock-mcp has no version flag; --help prints its flags and exits 1.
  formula sock-mcp mcp SockMcp "MCP server that lets an agent message through sock as a puppet" \
    'assert_match "outbound-only", shell_output("#{bin}/sock-mcp --help 2>&1", 1)'
  ;;
"cask sock") cask ;;
*) usage ;;
esac
